// Diccionario CURADO de aliases clínicos (propuesta para revisión humana; NADA de esto está en Supabase).
// Cada grupo apunta por "code" + "hint" (subcadena del normalized_name del estudio). Si el catálogo cambia y el hint
// ya no coincide, el motor lo reporta como error de curación y NO propone ese alias.
//
// Estados:
//  SEGURO             sinónimo/abreviatura estándar de ESE estudio y de ningún otro (exactamente 1 destino).
//  REQUIERE_REVISION  plausible, pero hay un matiz clínico o de política que debe decidir el laboratorio.
//  AMBIGUO            la forma corta puede referirse a varios estudios (≥2 destinos); NO se debe insertar tal cual.

export type CuratedState = "SEGURO" | "REQUIERE_REVISION" | "AMBIGUO";

export interface CuratedTarget {
  code: string;
  hint: string;
}

export interface CuratedGroup {
  status: CuratedState;
  targets: CuratedTarget[];
  aliases: string[];
  note?: string;
}

const S = (code: string, hint: string, aliases: string[], note?: string): CuratedGroup => ({
  status: "SEGURO",
  targets: [{ code, hint }],
  aliases,
  note
});
const R = (code: string, hint: string, aliases: string[], note: string): CuratedGroup => ({
  status: "REQUIERE_REVISION",
  targets: [{ code, hint }],
  aliases,
  note
});
const A = (targets: Array<[string, string]>, aliases: string[], note: string): CuratedGroup => ({
  status: "AMBIGUO",
  targets: targets.map(([code, hint]) => ({ code, hint })),
  aliases,
  note
});

